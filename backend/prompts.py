STAGE2_PROMPTS: dict[str, str] = {
    "v1": STAGE2_SYSTEM_V1,
    "v2": STAGE2_SYSTEM_V2,
    "v3": STAGE2_SYSTEM_V3,
    "v4": STAGE2_SYSTEM_V4,
    "v5": STAGE2_SYSTEM_V5,
    "v6": STAGE2_SYSTEM_V6,
    "v7": STAGE2_SYSTEM_V7,
}


def get_stage2_system(version: str) -> str:
    if version not in STAGE2_PROMPTS:
        raise ValueError(f"未知的评分 prompt 版本：{version}（可选 {', '.join(STAGE2_PROMPTS)}）")
    return STAGE2_PROMPTS[version]


def build_stage2_user_prompt(
    diary_id: str,
    text: str,
    grouped_segments: list[dict[str, object]],
) -> str:
    payload = json.dumps(grouped_segments, ensure_ascii=False, indent=2)
    return (
        f"日记编号：{diary_id}\n"
        "日记全文：\n"
        "<<<DIARY_START>>>\n"
        f"{text}\n"
        "<<<DIARY_END>>>\n\n"
        "阶段一自动标注的片段（按步骤分组，仅供参考）：\n"
        f"{payload}\n\n"
        "请按系统指令为全部五个步骤评定深度分并输出 JSON。"
    )
