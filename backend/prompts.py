CALIBRATION_GUIDE = """评分把握（与人工编码员对齐的通用尺度）

总原则：
- 0 分只给「完全没有涉及该步骤」的情况。只要有任何相关内容——哪怕是一句带过、笼统、零碎、隐含、语气犹豫（"也许""大概""可能"）、以感叹或反问的形式出现——就至少是 1 分。在 0 和 1 之间犹豫、且确有相关内容时，给 1。
- 2 分看的是「具体、清楚」，不看篇幅：一句话如果具体地、清楚地回答了该步骤的问题，就可以是 2；长篇但笼统、空泛、只是表态，仍然是 1。
- 每个步骤独立判断，同一句话可以同时支撑多个步骤。

各步骤的常见边界：
步骤1：只叙述做了什么、去了哪里，外加一句间接的喜好（"挺喜欢""还不错"）→ 1。写出了具体的情绪、念头、身体感受或内心活动（如紧张、烦躁、心里闷、一直在想……）→ 2。
步骤2：清楚指出了自身感受或行为的来由（某件事/某个人/自身状态导致了这个感受或做法），即使只有一句，只要因果清楚 → 2。原因只是隐约带到、解释不完整，或者解释的是对别人/事物的看法而不是自己的感受和做法，或者答非所问（只描述了做法而没说为什么）→ 1。
步骤3：明确说出学到了什么、明白了什么、得到了什么提醒或形成了清楚的新观点 → 2。只是回看时的感慨（如感叹时间、感叹生活、自嘲）、零散的体会、半成形的领悟、"如果当初……就好了"式的回想，或者说"没学到什么，但……"同时给出了一些回顾性的看法 → 1。明确表示没有任何收获且没有其他回顾内容 → 0。
步骤4：「价值观」指作者较持久的信念与原则——在乎什么、相信什么、想过什么样的生活、想成为什么样的人（如家人、诚信、真诚待人、健康、成长、过好当下、不攀比等）。不必出现"价值观"一词，但必须是作者自己表达出来的，而不是编码者从行为或情绪里推断出来的。
  · 不算价值观：一般的喜好、口味、兴趣爱好上的情怀（喜欢某部电影、想买某样东西）、做完某件事后的开心/踏实/满足感、仅仅提到"价值观"这个词或话题。这些单独出现时 → 0。
  · 作者表达了某种信念、人生态度或自己看重的东西（包括明确说"我很看重……"的喜好），但没有拿它去评判自己的做法；或只是把它和自己的做法并列、以反问或纠结的方式带出、在几种在乎之间犹豫取舍；或只笼统地说"和我的价值观有关" → 1。
  · 作者明确地用自己看重的东西去对照、评判自己当时（或一贯）的做法、想法：说清楚相符还是相悖、应不应该、以前怎么想现在怎么看 → 2。
  · 明确说"没什么关系"，或完全没有上述内容 → 0。
  · 问答型：问题里已经点明了当时的做法，答案只要清楚说出一个具体看重的价值（即使很短）就算建立了联系 → 2；只说"有关系""息息相关"而不说是什么 → 1。
  · 注意与步骤3区分：步骤3是"从这段经历中得到了什么"，步骤4是"自己的做法/想法与自己看重的东西是什么关系"。
步骤5：看内容是否说出了「自己会怎样做」，而不是看措辞：
  · 说出了自己以后会采取的做法、策略或行为方向（针对这类情境具体做什么、怎么调整），且指向改进、目标或自己看重的东西 → 2。即使用"希望自己……""尽量……"的语气，只要内容是明确的做法，也算 2。
  · 只盼望某种结果或状态出现（"希望下次顺利""盼着能好好休息""希望还能再来"），模糊的打算、把问题先放一放、对未来该怎么办的纠结自问、与成长目标无关的日常安排，或空泛的表态（"会换个角度""会注意"）→ 1。
  · 完全没有面向未来的内容 → 0。
问答型：只看对应的「答」。答得简短但具体切题（如直接说出一个明确的原因、一个明确看重的价值、一个明确的做法）→ 可以是 2；只表态、空泛 → 1；否认或完全不切题 → 0。
"""

